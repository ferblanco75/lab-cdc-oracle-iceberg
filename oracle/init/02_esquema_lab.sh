#!/bin/bash
# ---------------------------------------------------------------
# Esquema de ejemplo "LAB" en la PDB FREEPDB1.
# Datos ficticios inspirados en un dominio tributario:
#   CLIENTES (contribuyentes) y PAGOS (pagos de impuestos).
# ---------------------------------------------------------------
echo ">>> [lab] Creando esquema LAB con datos de prueba..."
sqlplus -s / as sysdba <<'SQL'
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER lab IDENTIFIED BY lab DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO lab;

CREATE TABLE lab.clientes (
  id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuit           VARCHAR2(13)  NOT NULL,
  razon_social   VARCHAR2(100) NOT NULL,
  provincia      VARCHAR2(40)  NOT NULL,
  actualizado_en DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE lab.pagos (
  id          NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id  NUMBER(10) NOT NULL REFERENCES lab.clientes(id),
  impuesto    VARCHAR2(30) NOT NULL,
  monto       NUMBER(14,2) NOT NULL,
  fecha_pago  DATE NOT NULL,
  estado      VARCHAR2(15) NOT NULL
);

-- Supplemental logging a nivel tabla: todas las columnas en cada cambio.
ALTER TABLE lab.clientes ADD SUPPLEMENTAL LOG DATA (ALL) COLUMNS;
ALTER TABLE lab.pagos    ADD SUPPLEMENTAL LOG DATA (ALL) COLUMNS;

-- Datos semilla: 50 clientes y 500 pagos
DECLARE
  TYPE t_txt IS TABLE OF VARCHAR2(40);
  provincias t_txt := t_txt('Buenos Aires','CABA','Cordoba','Santa Fe','Mendoza',
                            'Tucuman','Neuquen','Salta','Chubut','Entre Rios');
  impuestos  t_txt := t_txt('IVA','GANANCIAS','BIENES_PERSONALES','MONOTRIBUTO','SEG_SOCIAL');
  estados    t_txt := t_txt('ACREDITADO','ACREDITADO','ACREDITADO','PENDIENTE','RECHAZADO');
BEGIN
  FOR i IN 1..50 LOOP
    INSERT INTO lab.clientes (cuit, razon_social, provincia)
    VALUES ('30-' || LPAD(TRUNC(DBMS_RANDOM.VALUE(10000000, 99999999)), 8, '0') || '-' || MOD(i, 10),
            'Contribuyente Ficticio ' || i,
            provincias(TRUNC(DBMS_RANDOM.VALUE(1, 11))));
  END LOOP;
  FOR i IN 1..500 LOOP
    INSERT INTO lab.pagos (cliente_id, impuesto, monto, fecha_pago, estado)
    VALUES (TRUNC(DBMS_RANDOM.VALUE(1, 51)),
            impuestos(TRUNC(DBMS_RANDOM.VALUE(1, 6))),
            ROUND(DBMS_RANDOM.VALUE(1000, 500000), 2),
            TRUNC(SYSDATE) - TRUNC(DBMS_RANDOM.VALUE(0, 180)),
            estados(TRUNC(DBMS_RANDOM.VALUE(1, 6))));
  END LOOP;
  COMMIT;
END;
/
SELECT 'clientes=' || COUNT(*) FROM lab.clientes;
SELECT 'pagos='    || COUNT(*) FROM lab.pagos;
SQL
echo ">>> [lab] Esquema LAB listo."
